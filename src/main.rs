fn compile_and_run() -> io::Result<()> {
    // 1. Compile C code
    let compile_status = Command::new("gcc")
        .args(["output.c", "-o", "output"])
        .status()?;

    if !compile_status.success() {
        panic!("GCC compilation failed");
    }

    // 2. Run program
    let run_status = Command::new("./output").status()?;

    if !run_status.success() {
        panic!("Program execution failed");
    }

    Ok(())
}
